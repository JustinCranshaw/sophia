#!/usr/bin/env python3
"""Generate the static native DC mark; run from any directory. No runtime SVG parser."""
from pathlib import Path
import hashlib, math, re, sys
root = Path(__file__).resolve().parents[2]
source = (root / "docs/sophia-wordmark-options.html").read_text()
symbol = re.search(r'<symbol id="sDC" viewBox="0 0 32 32">.*?</symbol>', source).group()
paths = re.findall(r'<path d="([^"]+)"', symbol)
assert len(paths) == 6 and 'scale(0.16)' in symbol
lines = ["// Generated by app/scripts/gen-brand-mark.py — do not edit.",
         "// Exact DC source: docs/sophia-wordmark-options.html, base orientation.",
         "// Source symbol SHA-256: " + hashlib.sha256(symbol.encode()).hexdigest(),
         "import SwiftUI", "", "struct BrandMark: Shape {",
         "    static let unitPath: Path = {", "        var path = Path()"]
def num(v): return format(v, ".17g")
def point(x,y): return f"CGPoint(x: {num(x)}, y: {num(y)})"
for d in paths:
    ts = re.findall(r"[MLAZ]|[-+]?(?:\d*\.\d+|\d+)(?:[eE][-+]?\d+)?", d)
    i=0; current=None
    while i<len(ts):
        command=ts[i];i+=1
        if command in ("M","L"):
            x,y=map(float,ts[i:i+2]);i+=2;current=(x,y)
            lines.append(f"        path.{'move' if command=='M' else 'addLine'}(to: {point(x,y)})")
        elif command=="Z": lines.append("        path.closeSubpath()")
        elif command=="A":
            rx,ry,rotation,large,sweep,x,y=map(float,ts[i:i+7]);i+=7
            assert rx==ry and rotation==0 and large in (0,1) and sweep in (0,1)
            x0,y0=current;dx,dy=(x0-x)/2,(y0-y)/2;q=dx*dx+dy*dy
            assert q>0 and q<=rx*rx+1e-8
            factor=math.sqrt(max(0,(rx*rx-q)/q))*(-1 if large==sweep else 1)
            cx,cy=(x0+x)/2+factor*dy,(y0+y)/2-factor*dx
            start=math.atan2(y0-cy,x0-cx);end=math.atan2(y-cy,x-cx)
            delta=(end-start)%(2*math.pi)
            if not sweep and delta>0:delta-=2*math.pi
            lines.append(f"        path.addArc(center: {point(cx,cy)}, radius: {num(rx)}, startAngle: .radians({num(start)}), endAngle: .radians({num(start+delta)}), clockwise: {'true' if not sweep else 'false'})")
            current=(x,y)
        else: raise ValueError(command)
lines += ["        return path", "    }()", "", "    func path(in rect: CGRect) -> Path {",
          "        let side = min(rect.width, rect.height)", "        let scale = side / 200",
          "        return Self.unitPath.applying(CGAffineTransform(a: scale, b: 0, c: 0, d: scale,",
          "            tx: rect.midX - side / 2, ty: rect.midY - side / 2))", "    }", "}", ""]
target = root / "app/Sources/Sophia/BrandMarkPath.swift"
result = "\n".join(lines)
if sys.argv[1:] == ["--check"]:
    if target.read_text() != result:
        raise SystemExit("BrandMarkPath.swift differs from the locked source; regenerate it.")
    print("Exact DC generation parity: 6 paths, 36 circular arcs; generated file matches.")
elif sys.argv[1:]:
    raise SystemExit("Usage: gen-brand-mark.py [--check]")
else:
    target.write_text(result)
